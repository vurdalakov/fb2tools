namespace Vurdalakov
{
    using System;
    using System.IO;
    using System.Text;

    internal static class WebhookGenerator
    {
        // The webhook must re-invoke itself with --webhook-token included, or the very next
        // rebuild (triggered by itself) would regenerate the catalog without this file.
        public static void Write(SiteInfo siteInfo, String baseDirectoryPath, String baseUrl, String catalogName, String webhookToken)
        {
            var executableTokens = GetSelfInvocationCommand();

            var libraryArgs = new[]
            {
                "--path", baseDirectoryPath,
                "--url", baseUrl,
                "--name", catalogName,
                "--webhook-token", webhookToken,
            };

            var lockFilePath = Path.Combine(Path.GetTempPath(), "opds-rebuild.lock");
            var logFilePath = Path.Combine(siteInfo.OpdsBaseDirectoryPath, "rebuild.log");

            var script = BuildScript(webhookToken, executableTokens, libraryArgs, lockFilePath, logFilePath);
            File.WriteAllText(Path.Combine(siteInfo.OpdsBaseDirectoryPath, "rebuild.php"), script);

            // Keep the log out of public reach; it can contain internal paths and error details.
            var htaccessFilePath = Path.Combine(siteInfo.OpdsBaseDirectoryPath, ".htaccess");
            File.AppendAllText(htaccessFilePath, "\n<Files \"rebuild.log\">\n    Require all denied\n</Files>\n");
        }

        // Works out how to re-launch the currently running process: "dotnet /path/App.dll" for a
        // framework-dependent deployment, or just the executable path for a self-contained one.
        private static String[] GetSelfInvocationCommand()
        {
            var processPath = Environment.ProcessPath;

            // Started as "dotnet App.dll": the process is the dotnet host and the first command line argument is the dll.
            // Started as an executable (apphost or single-file): the process itself is the app.
            var isDotnetHost = String.Equals(Path.GetFileNameWithoutExtension(processPath), "dotnet", StringComparison.OrdinalIgnoreCase);

            return isDotnetHost ? new[] { processPath, Path.GetFullPath(Environment.GetCommandLineArgs()[0]) } : new[] { processPath };
        }

        private static String PhpString(String value) => "'" + value.Replace("\\", "\\\\").Replace("'", "\\'") + "'";

        private static String PhpArray(String[] values)
        {
            var builder = new StringBuilder("[");

            for (var i = 0; i < values.Length; i++)
            {
                if (i > 0)
                {
                    builder.Append(", ");
                }

                builder.Append(PhpString(values[i]));
            }

            builder.Append(']');

            return builder.ToString();
        }

        private static String BuildScript(String webhookToken, String[] executableTokens, String[] libraryArgs, String lockFilePath, String logFilePath) => Template
            .Replace("{{GENERATED_AT}}", DateTime.UtcNow.ToString("o"))
            .Replace("{{SECRET_TOKEN}}", PhpString(webhookToken))
            .Replace("{{EXECUTABLE}}", PhpArray(executableTokens))
            .Replace("{{LIBRARY_ARGS}}", PhpArray(libraryArgs))
            .Replace("{{LOCK_FILE}}", PhpString(lockFilePath))
            .Replace("{{LOG_FILE}}", PhpString(logFilePath));

        private const String Template = @"<?php

declare(strict_types=1);

// Auto-generated by Fb2Opds on {{GENERATED_AT}} UTC.
// Regenerated on every rebuild that includes --webhook-token - do not edit by hand.
// A rebuild that omits --webhook-token removes this file.

const SECRET_TOKEN = {{SECRET_TOKEN}};
const EXECUTABLE   = {{EXECUTABLE}};
const LIBRARY_ARGS = {{LIBRARY_ARGS}};
const LOCK_FILE    = {{LOCK_FILE}};
const LOG_FILE     = {{LOG_FILE}};

// ---- Auth ----
// OPDS_REBUILD_TOKEN, if set in the web server's environment, overrides SECRET_TOKEN -
// lets you rotate the token without waiting for the next rebuild.
$token = getenv('OPDS_REBUILD_TOKEN');
$secret = ($token !== false) && ($token !== '') ? $token : SECRET_TOKEN;

$provided = $_SERVER['HTTP_X_REBUILD_TOKEN'] ?? ($_GET['token'] ?? '');
if (!hash_equals($secret, (string) $provided)) {
    http_response_code(403);
    header('Content-Type: text/plain');
    exit(""Forbidden\n"");
}

if (($_SERVER['REQUEST_METHOD'] ?? 'GET') !== 'POST') {
    http_response_code(405);
    header('Allow: POST');
    header('Content-Type: text/plain');
    exit(""Use POST\n"");
}

// ---- Launch the rebuild as a detached background process ----
// `flock -n LOCK_FILE <argv...>` runs the command directly (no shell re-parsing of its
// arguments) and holds an exclusive lock for as long as it runs; a second request arriving
// mid-rebuild fails to acquire the lock and is skipped instead of overlapping it.
// `nohup` + trailing `&` detach the process so it outlives this request.
$tokens = array_merge(['nohup', 'flock', '-n', LOCK_FILE], EXECUTABLE, LIBRARY_ARGS);
$command = implode(' ', array_map('escapeshellarg', $tokens)) . ' >> ' . escapeshellarg(LOG_FILE) . ' 2>&1 &';
shell_exec($command);

http_response_code(202);
header('Content-Type: text/plain');
echo ""Rebuild triggered. If one was already running, this request was skipped instead of overlapping it.\n"";
";
    }
}
